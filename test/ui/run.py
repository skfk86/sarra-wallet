import asyncio, sys
from playwright.async_api import async_playwright
S=sys.argv[1]
async def main():
  async with async_playwright() as p:
    b=await p.chromium.launch()
    pg=await b.new_page(viewport={'width':390,'height':844})
    errs=[]
    pg.on('pageerror',lambda e: errs.append(str(e)))
    # history fetch stub
    await pg.route('**/v1/accounts/**', lambda r: r.fulfill(json={'data':[{'transaction_id':'abc','to':'TQ7mZ4bR8xLkP2vN9cW3jH5sD6fGa19xKf','from':'TK3aZ4bR8xLkP2vN9cW3jH5sD6fGa12pLw','value':'250000000','token_info':{'decimals':6},'block_timestamp':1760000000000}]}))
    await pg.goto('file://'+S+'/index.html')
    async def vis(i): return await pg.locator('#'+i).is_visible()
    async def pin(d):
      for c in d: await pg.click(f'#keypad button:text-is("{c}")')
      await pg.wait_for_timeout(2500)
    step=lambda m: print('✓',m)
    assert await vis('s-welcome'); step('شاشة الترحيب')
    await pg.click('[data-go=create]')
    assert 'river' not in await pg.inner_text('#words'); step('الكلمات مخفية قبل الإظهار')
    await pg.click('#reveal'); assert not await vis('reveal'); assert 'river' in await pg.inner_text('#words'); step('الإظهار يعمل والزر يختفي')
    assert await pg.is_disabled('#backup-next'); await pg.check('#agree'); await pg.click('#backup-next')
    await pin('123456'); await pin('654321')
    assert 'غير متطابقين' in await pg.inner_text('#pin-err'); step('رفض رمزين غير متطابقين')
    await pin('123456'); await pin('123456')
    await pg.wait_for_timeout(1500)
    assert await vis('s-home'); step('إنشاء المحفظة والدخول للرئيسية')
    assert await vis('intro-sheet'); await pg.click('#intro-ok'); step('نافذة قبل أن تبدأ تظهر مرة واحدة')
    t=await pg.inner_text('#bal-usdt'); assert '125.50' in t, t; step('عرض الرصيد '+t)
    assert not await vis('low-trx'); step('لا تحذير رسوم مع 50 TRX')
    assert 'استلام' in await pg.inner_text('#history'); step('السجل في الرئيسية')
    await pg.click('.actions [data-go=receive]'); assert 'TQ7m' in await pg.inner_text('#addr'); step('شاشة الاستلام'); await pg.click('#s-receive [data-back]')
    await pg.click('.actions [data-go=send]')
    await pg.fill('#to','bad'); await pg.fill('#amt','10'); await pg.click('#review'); assert await vis('send-err'); step('رفض عنوان غير صالح')
    await pg.fill('#to','TQ7mZ4bR8xLkP2vN9cW3jH5sD6fGa19xKf'); await pg.click('#review'); await pg.click('#confirm-send'); await pin('123456')
    await pg.wait_for_timeout(5000)
    assert await vis('send-err') and 'نفس محفظتك' in await pg.inner_text('#send-err'), await pg.inner_text('#send-err'); step('منع الإرسال لنفس المحفظة')
    await pg.fill('#to','TK3aZ4bR8xLkP2vN9cW3jH5sD6fGa12pLw'); await pg.fill('#amt','999'); await pg.click('#review'); assert 'غير كافٍ' in await pg.inner_text('#send-err'); step('رفض مبلغ أكبر من الرصيد')
    await pg.fill('#amt','12.5'); await pg.click('#review'); assert await vis('sheet'); step('ورقة التأكيد')
    await pg.click('#confirm-send')
    # ضغط سريع مزدوج على الأرقام بعد الاكتمال
    for c in '123456': await pg.click(f'#keypad button:text-is("{c}")')
    for c in '123456': await pg.click(f'#keypad button:text-is("{c}")', no_wait_after=True)
    await pg.wait_for_timeout(8000)
    sent=await pg.evaluate('window.__sent'); assert len(sent)==1, sent; step('إرسال واحد فقط رغم الضغط المزدوج: '+str(sent))
    assert await vis('s-success'); step('شاشة النجاح: '+await pg.inner_text('#ok-title'))
    await pg.click('#s-success [data-go=home]')
    await pg.click('.tab[data-tab=history]'); await pg.wait_for_timeout(500); assert '250' in await pg.inner_text('#history-full'); step('شاشة السجل')
    await pg.click('[data-filter=out]'); assert 'لا توجد' in await pg.inner_text('#history-full'); step('تصفية السجل')
    await pg.click('.tab[data-tab=security]'); await pg.click('#sec-reveal'); await pin('000000')
    assert 'غير صحيح' in await pg.inner_text('#pin-err'); step('رفض رمز خاطئ في عرض الكلمات')
    await pin('123456'); assert await vis('s-reveal') and 'river' in await pg.inner_text('#words2'); step('عرض الكلمات بعد الرمز')
    await pg.click('#reveal-done'); assert await pg.inner_text('#words2')=='' ; step('مسح الكلمات من الشاشة بعد الخروج')
    await pg.click('#sec-pin'); await pin('123456'); await pin('111111'); await pin('111111'); await pg.wait_for_timeout(2000)
    assert await vis('s-security'); step('تغيير الرمز')
    await pg.click('#lock-now'); await pin('123456'); assert await vis('s-pin'); step('الرمز القديم مرفوض بعد التغيير')
    assert await vis('forgot-pin'); step('زر نسيت الرمز')
    for i in range(4): await pin('999999')
    await pg.wait_for_timeout(500)
    e=await pg.inner_text('#pin-err'); assert 'دقيقة' in e, e; step('الحظر بعد 5 محاولات: '+e)
    await pg.reload(); await pg.wait_for_timeout(1500); await pin('111111')
    e=await pg.inner_text('#pin-err'); assert 'دقيقة' in e, e; step('الحظر يبقى بعد إعادة التشغيل')
    await pg.click('#forgot-pin'); await pg.click('#forgot-yes'); await pg.wait_for_timeout(800)
    assert await vis('s-import'); step('نسيت الرمز ← الاستيراد')
    await pg.fill('#mn-in','river smile cotton eagle harvest lamp orbit velvet sand thunder maple quiet'); await pg.click('#import-next')
    await pin('222222'); await pin('222222'); await pg.wait_for_timeout(1500); assert await vis('s-home'); step('الاستيراد برمز جديد بعد الحظر')
    await pg.click('.actions [data-go=swap]'); await pg.wait_for_timeout(500); assert await vis('swap-off'); step('التبديل معطّل على Nile برسالة واضحة')
    print('\nأخطاء JavaScript:', errs or 'لا يوجد')
    await b.close()
asyncio.run(main())
